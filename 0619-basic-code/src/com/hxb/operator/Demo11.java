package com.hxb.operator;

public class Demo11 {
    public static void main(String[] args) {

        /**
         * while循环
         * do-while循环
         */

        int i = 1;
        while (i <= 10) {
            System.out.println(i);
            i++;
        }

        i = 1;
        do{
            System.out.println(i);
            i++;
        }while (i <= 10);
    }
}
