package com.hxb.operator;

public class Demo10 {
    public static void main(String[] args) {

        /**
         * for循环
         */


        /**
         * 执行流程：
         * 1. 初始化循环变量i = 1
         * 2. 判断循环条件i <= 10
         * 3. 执行循环体代码
         * 4. 更新循环变量i = i + 1
         * 5. 重复以上步骤，直到循环条件不满足
         * 6. 循环结束
         */
        for (int i = 1; i <= 10; i++) {
            System.out.println(i);
        }
    }
}
