package com.hxb.operator;

public class Demo06 {
    public static void main(String[] args) {

        /**
         * if语句
         */

        // 练习：定义一个变量表示人的体温，判断体温是否大于等于38度，如果超过打印语音警告

        // 1.定义一个变量表示人的体温
        double temperature = 37.5;

        // 2. 利用if语句判断体温是否大于等于38度
        if (temperature >= 38.0) {
            System.out.println("体温超过38度，注意健康！");
        }
    }
}
