//package:表示当前的类定义在哪个包下
package com.helloworld;

//class:表示定义一个类。类是java项目中最基本的组成单位。
//HelloWorld:类的名字
//{}:表示类的范围，所有的代码都需要写在{}中
public class HelloWorld {

    //表示java程序的主入口，当程序开始运行的时候，会从主入口开始逐行往下执行，它是一个固定格式，不能修改
    public static void main(String[] args) {

        //输出语句/打印语句，表示将里面的内容输出到控制台
        System.out.println("HelloWorld");

    }
}
